from __future__ import annotations

import re
from collections import OrderedDict


class InterfaceCatalogFormatter:
    """Normalizes generated interface catalog markdown to the approved style.

    This post-processing layer enforces:
    - left-aligned content (no leading indentation)
    - `*` bullets in all numbered sections
    - removal of generation-noise lines such as timestamps/version banners
    - stable section ordering and spacing that matches the approved reference style
    """

    SECTION_ORDER = [
        "1. PURPOSE",
        "2. SCOPE",
        "3. KEY TERMS",
        "4. CORE EXPLANATION",
        "5. OPERATIONAL RELEVANCE",
        "6. RELATED ARTIFACTS",
    ]

    FORBIDDEN_LINE_PATTERNS = [
        re.compile(r"^[-*]\s*Generated by MCP knowledge orchestration.*$", re.IGNORECASE),
        re.compile(r"^[-*]\s*Generated at:.*$", re.IGNORECASE),
    ]

    METADATA_RE = re.compile(r"^(?P<key>[a-z_]+):\s*\"?(?P<value>.*?)\"?$", re.IGNORECASE)
    SECTION_RE = re.compile(r"^\d+\.\s+.+$")

    def format_document(self, text: str) -> str:
        title, metadata, doc_id, doc_title, sections = self._parse(text)
        return self._render(
            title=title,
            metadata=metadata,
            doc_id=doc_id,
            doc_title=doc_title,
            sections=sections,
        )

    def _parse(self, text: str) -> tuple[str, OrderedDict[str, str], str, str, OrderedDict[str, list[str]]]:
        lines = [line.rstrip() for line in text.replace("\r\n", "\n").replace("\r", "\n").split("\n")]

        title = ""
        metadata: OrderedDict[str, str] = OrderedDict()
        doc_id = ""
        doc_title = ""
        sections: OrderedDict[str, list[str]] = OrderedDict((name, []) for name in self.SECTION_ORDER)

        idx = 0
        while idx < len(lines) and not lines[idx].strip():
            idx += 1

        if idx < len(lines) and lines[idx].lstrip().startswith("# "):
            title = lines[idx].lstrip()[2:].strip()
            idx += 1

        while idx < len(lines):
            stripped = lines[idx].strip()
            if not stripped:
                idx += 1
                continue
            match = self.METADATA_RE.match(stripped)
            if not match:
                break
            metadata[match.group("key")] = match.group("value")
            idx += 1

        # Parse DOC ID / DOC TITLE blocks if present.
        while idx < len(lines):
            stripped = lines[idx].strip()
            if not stripped:
                idx += 1
                continue
            if stripped == "DOC ID":
                idx += 1
                while idx < len(lines) and not lines[idx].strip():
                    idx += 1
                if idx < len(lines):
                    doc_id = lines[idx].strip()
                    idx += 1
                continue
            if stripped == "DOC TITLE":
                idx += 1
                while idx < len(lines) and not lines[idx].strip():
                    idx += 1
                if idx < len(lines):
                    doc_title = lines[idx].strip()
                    idx += 1
                continue
            if self.SECTION_RE.match(stripped):
                break
            idx += 1

        current_section: str | None = None
        while idx < len(lines):
            stripped = lines[idx].strip()
            idx += 1
            if not stripped:
                continue
            if self.SECTION_RE.match(stripped):
                current_section = stripped
                sections.setdefault(current_section, [])
                continue
            if current_section is None:
                continue
            cleaned = self._clean_section_line(stripped)
            if cleaned:
                sections[current_section].append(cleaned)

        # Fallbacks
        object_name = metadata.get("object_name", "UNKNOWN_OBJECT")
        if not title:
            title = metadata.get("integration_flow_name") or metadata.get("interface_id") or object_name
        if not doc_id:
            sap_sid = metadata.get("sap_sid", "CPI")
            doc_id = f"CAT-{sap_sid}-{object_name}"
        if not doc_title:
            doc_title = title

        return title, metadata, doc_id, doc_title, sections

    def _clean_section_line(self, line: str) -> str | None:
        stripped = line.strip()
        if not stripped:
            return None
        for pattern in self.FORBIDDEN_LINE_PATTERNS:
            if pattern.match(stripped):
                return None
        stripped = re.sub(r"^[*-]\s*", "", stripped)
        stripped = re.sub(r"^\d+\.\s*", "", stripped)
        stripped = re.sub(r"\s+", " ", stripped).strip()
        return stripped or None

    def _render(
        self,
        *,
        title: str,
        metadata: OrderedDict[str, str],
        doc_id: str,
        doc_title: str,
        sections: OrderedDict[str, list[str]],
    ) -> str:
        esc = lambda value: str(value).replace("_", r"\_")
        parts: list[str] = [f"# {esc(title)}", ""]

        if metadata:
            for key, value in metadata.items():
                parts.append(f'{esc(key)}: "{esc(value)}"')
            parts.append("")

        parts.extend(["DOC ID", esc(doc_id), "", "DOC TITLE", esc(doc_title), ""])

        for section_name in self.SECTION_ORDER:
            parts.append(section_name)
            lines = sections.get(section_name, [])
            if lines:
                parts.extend(f"* {esc(line)}" for line in lines)
            else:
                parts.append("* None")

        return "\n".join(parts).rstrip() + "\n"
