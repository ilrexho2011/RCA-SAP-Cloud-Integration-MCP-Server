
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Iterable, cast

from docx import Document as create_document
from docx.document import Document as DocxDocument
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt
from docx.styles.style import ParagraphStyle

try:
    from app.services.scoring_documentation_integration import (
        EnterpriseScoringDocumentationAdapter,
    )
except Exception:  # pragma: no cover - compatibility fallback
    try:
        from scoring_documentation_integration import (  # type: ignore
            EnterpriseScoringDocumentationAdapter,
        )
    except Exception:  # pragma: no cover - adapter optional
        EnterpriseScoringDocumentationAdapter = None  # type: ignore[assignment]


class DocxService:
    def __init__(self, output_dir: str | Path = "output/docx") -> None:
        self.output_dir = Path(output_dir)

    def generate_iflow_docx(
        self,
        iflow_id: str,
        analysis: Any,
        quality: Any | None = None,
        package_id: str | None = None,
        template_name: str = "sap_enterprise_v1",
        include_cover_page: bool = True,
        documentation_payload: dict[str, Any] | None = None,
        mcp_output: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        self.output_dir.mkdir(parents=True, exist_ok=True)

        filename = f"{self._slugify(iflow_id)}.docx"
        output_path = self.output_dir / filename

        doc = create_document()
        self._set_default_style(doc)

        if include_cover_page:
            self._add_cover_page(doc, iflow_id, template_name)

        sections: list[str] = []

        self._add_overview_section(
            doc=doc,
            iflow_id=iflow_id,
            analysis=analysis,
            package_id=package_id,
            template_name=template_name,
        )
        sections.append("Overview")

        self._add_analysis_section(doc=doc, analysis=analysis)
        sections.append("Analysis")

        resolved_payload = self._resolve_documentation_payload(
            iflow_id=iflow_id,
            analysis=analysis,
            quality=quality,
            documentation_payload=documentation_payload,
        )

        if resolved_payload is not None:
            self._add_enterprise_scoring_section(doc=doc, payload=resolved_payload)
            sections.append("Enterprise Scoring and Audit Assessment")
        elif quality is not None:
            self._add_quality_fallback_section(doc=doc, quality=quality)
            sections.append("Quality Findings")

        if mcp_output is not None:
            self._add_mcp_snapshot_section(doc=doc, mcp_output=mcp_output)
            sections.append("MCP Output Snapshot")

        sections.append("Technical Notes")
        doc.add_heading(f"{len(sections)}. Technical Notes", level=1)
        doc.add_paragraph(
            "This document was generated automatically by the SAP CPI MCP Server."
        )
        doc.add_paragraph(
            "Assessment quality depends on the selected analysis mode and the visibility "
            "of technical evidence exposed by the SAP tenant."
        )

        doc.save(str(output_path))

        return {
            "output_path": str(output_path),
            "filename": filename,
            "sections": sections,
        }

    def _add_cover_page(
        self,
        doc: DocxDocument,
        iflow_id: str,
        template_name: str = "sap_enterprise_v1",
    ) -> None:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER

        r = p.add_run("SAP Cloud Integration - Technical Documentation")
        r.bold = True
        r.font.size = Pt(20)

        p2 = doc.add_paragraph()
        p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p2.add_run(f"iFlow: {iflow_id}")

        p3 = doc.add_paragraph()
        p3.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p3.add_run(f"Template: {template_name}")

        p4 = doc.add_paragraph()
        p4.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p4.add_run("Generated by MCP Server").italic = True

        doc.add_page_break()

    def _add_overview_section(
        self,
        doc: DocxDocument,
        iflow_id: str,
        analysis: Any,
        package_id: str | None,
        template_name: str,
    ) -> None:
        doc.add_heading("1. Overview", level=1)

        table = doc.add_table(rows=1, cols=2)
        table.style = "Table Grid"
        table.rows[0].cells[0].text = "Field"
        table.rows[0].cells[1].text = "Value"

        overview_rows = [
            ("Integration Flow ID", iflow_id),
            ("Template Name", template_name),
            ("Analysis Mode", self._extract_analysis_mode(analysis)),
            ("Package ID", package_id or self._extract_first(analysis, "package_id", "package_name", "package")),
            ("Resolved Version", self._extract_first(analysis, "resolved_version", "version", "artifact_version")),
        ]

        for key, value in overview_rows:
            row = table.add_row().cells
            row[0].text = str(key)
            row[1].text = self._to_text(value)

        summary = self._extract_first(analysis, "summary")
        if summary:
            doc.add_paragraph(str(summary))

    def _add_analysis_section(self, doc: DocxDocument, analysis: Any) -> None:
        doc.add_heading("2. Analysis", level=1)

        if isinstance(analysis, dict):
            summary = self._extract_first(analysis, "summary")
            if summary:
                doc.add_paragraph(str(summary))

            snapshot = [
                ("Sender Systems", self._join_values(analysis.get("sender_systems"))),
                ("Receiver Systems", self._join_values(analysis.get("receiver_systems"))),
                ("Protocols", self._join_values(analysis.get("protocols"))),
                ("Authentication", self._join_values(analysis.get("authentication"))),
                ("Package", self._extract_first(analysis, "package_name", "package")),
                ("Version", self._extract_first(analysis, "resolved_version", "version")),
            ]

            table = doc.add_table(rows=1, cols=2)
            table.style = "Table Grid"
            table.rows[0].cells[0].text = "Signal"
            table.rows[0].cells[1].text = "Value"
            for key, value in snapshot:
                row = table.add_row().cells
                row[0].text = str(key)
                row[1].text = self._to_text(value)

            doc.add_paragraph("Raw Analysis Snapshot")
            doc.add_paragraph(self._to_pretty_json(analysis))
            return

        doc.add_paragraph(self._to_text(analysis))

    def _add_enterprise_scoring_section(
        self,
        doc: DocxDocument,
        payload: dict[str, Any],
    ) -> None:
        doc.add_heading("3. Enterprise Scoring and Audit Assessment", level=1)

        blocks = payload.get("section_blocks", [])
        if not isinstance(blocks, list):
            doc.add_paragraph(self._to_pretty_json(payload))
            return

        for block in blocks:
            title = self._block_value(block, "title")
            kind = self._block_value(block, "kind")
            content = self._block_value(block, "content")

            if title:
                doc.add_heading(str(title), level=2)

            if kind == "paragraph":
                doc.add_paragraph(self._to_text(content))
            elif kind == "bullets":
                for item in self._as_list(content):
                    doc.add_paragraph(self._to_text(item), style="List Bullet")
            elif kind == "key_value":
                rows = self._normalize_key_value_rows(content)
                self._render_table(doc, ["Metric", "Value"], rows)
            elif kind == "table":
                columns = list(self._block_value(content, "columns") or [])
                rows = list(self._block_value(content, "rows") or [])
                normalized_rows = [
                    [self._to_text(row.get(column, "")) if isinstance(row, dict) else "" for column in columns]
                    for row in rows
                ]
                self._render_table(doc, [str(col) for col in columns], normalized_rows)
            else:
                doc.add_paragraph(self._to_text(content))

    def _add_quality_fallback_section(self, doc: DocxDocument, quality: Any) -> None:
        doc.add_heading("3. Quality Findings", level=1)
        if isinstance(quality, dict):
            summary = quality.get("summary")
            if summary:
                doc.add_paragraph(str(summary))
            doc.add_paragraph(self._to_pretty_json(quality))
            return
        doc.add_paragraph(self._to_text(quality))

    def _add_mcp_snapshot_section(
        self,
        doc: DocxDocument,
        mcp_output: dict[str, Any],
    ) -> None:
        doc.add_heading("4. MCP Output Snapshot", level=1)

        summary_rows = [
            ("Tool", mcp_output.get("tool")),
            ("Version", mcp_output.get("version")),
            ("Generated At (UTC)", mcp_output.get("generated_at_utc")),
            ("iFlow ID", self._nested_get(mcp_output, "iflow", "id")),
            ("Analysis Mode", self._nested_get(mcp_output, "iflow", "analysis_mode")),
            ("Score", self._nested_get(mcp_output, "scoring", "score")),
            ("Confidence Level", self._nested_get(mcp_output, "scoring", "confidence_level")),
        ]
        self._render_table(
            doc,
            ["Field", "Value"],
            [[str(key), self._to_text(value)] for key, value in summary_rows],
        )

        doc.add_paragraph("JSON Snapshot")
        doc.add_paragraph(self._to_pretty_json(mcp_output))

    def _resolve_documentation_payload(
        self,
        iflow_id: str,
        analysis: Any,
        quality: Any | None,
        documentation_payload: dict[str, Any] | None,
    ) -> dict[str, Any] | None:
        if isinstance(documentation_payload, dict):
            return documentation_payload

        if isinstance(quality, dict):
            embedded = quality.get("documentation_payload")
            if isinstance(embedded, dict):
                return embedded

        if not isinstance(analysis, dict) or not isinstance(quality, dict):
            return None

        if EnterpriseScoringDocumentationAdapter is None:
            return None

        try:
            adapter = EnterpriseScoringDocumentationAdapter()
            return adapter.build_documentation_payload(
                iflow_id=iflow_id,
                analysis=analysis,
                scoring_result=quality,
            )
        except Exception:
            return None

    def _render_table(
        self,
        doc: DocxDocument,
        headers: list[str],
        rows: list[list[str]],
    ) -> None:
        if not headers:
            return

        table = doc.add_table(rows=1, cols=len(headers))
        table.style = "Table Grid"
        for idx, header in enumerate(headers):
            table.rows[0].cells[idx].text = str(header)

        for row_values in rows:
            row = table.add_row().cells
            for idx, value in enumerate(row_values[: len(headers)]):
                row[idx].text = self._to_text(value)

    def _normalize_key_value_rows(self, content: Any) -> list[list[str]]:
        rows: list[list[str]] = []
        for item in self._as_list(content):
            if isinstance(item, dict):
                rows.append(
                    [
                        self._to_text(item.get("key")),
                        self._to_text(item.get("value")),
                    ]
                )
            else:
                rows.append([self._to_text(item), ""])
        return rows

    def _extract_analysis_mode(self, analysis: Any) -> str:
        if isinstance(analysis, dict):
            mode = self._extract_first(
                analysis,
                "analysis_mode",
                "mode",
                "parser_mode",
                "extraction_mode",
            )
            if mode:
                return str(mode)
            summary = str(analysis.get("summary", "")).lower()
            if "metadata_only" in summary:
                return "metadata_only"
            if "zip_based" in summary:
                return "zip_based"
        return "unknown"

    def _extract_first(self, data: Any, *keys: str) -> Any:
        if not isinstance(data, dict):
            return None
        for key in keys:
            value = data.get(key)
            if value not in (None, "", [], {}, ()):
                return value
        return None

    def _join_values(self, value: Any) -> str:
        if value is None:
            return "N/A"
        if isinstance(value, (list, tuple, set)):
            values = [str(item).strip() for item in value if str(item).strip()]
            return ", ".join(values) if values else "N/A"
        text = str(value).strip()
        return text or "N/A"

    def _as_list(self, value: Any) -> list[Any]:
        if value is None:
            return []
        if isinstance(value, list):
            return value
        if isinstance(value, tuple):
            return list(value)
        return [value]

    def _block_value(self, obj: Any, key: str) -> Any:
        if hasattr(obj, key):
            return getattr(obj, key)
        if isinstance(obj, dict):
            return obj.get(key)
        return None

    def _nested_get(self, data: dict[str, Any], *keys: str) -> Any:
        current: Any = data
        for key in keys:
            if not isinstance(current, dict):
                return None
            current = current.get(key)
        return current

    def _set_default_style(self, doc: DocxDocument) -> None:
        style = cast(ParagraphStyle, doc.styles["Normal"])
        style.font.name = "Arial"
        style.font.size = Pt(10)

    def _slugify(self, value: str) -> str:
        value = value.strip()
        value = re.sub(r"[^A-Za-z0-9_.-]+", "_", value)
        return value or "iflow_documentation"

    def _to_pretty_json(self, value: Any) -> str:
        try:
            return json.dumps(value, indent=2, ensure_ascii=False, default=str)
        except Exception:
            return str(value)

    def _to_text(self, value: Any) -> str:
        if value is None:
            return "N/A"
        if isinstance(value, str):
            return value
        if isinstance(value, (dict, list, tuple, set)):
            return self._to_pretty_json(value)
        return str(value)
